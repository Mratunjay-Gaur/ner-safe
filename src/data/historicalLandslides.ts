/**
 * Helper to query historical landslides by district or state
 */
export function getLandslidesForDistrict(districtName: string, stateName: string): HistoricalLandslideRecord[] {
  const normDist = districtName.toLowerCase().trim();
  const normState = stateName.toLowerCase().trim();

  // 1. Direct district match
  const districtMatches = VERIFIED_NER_HISTORICAL_LANDSLIDES.filter(
    (item) => item.district.toLowerCase().trim() === normDist && item.state.toLowerCase().trim() === normState
  );

  if (districtMatches.length > 0) {
    return districtMatches;
  }

  // 2. Proximity radius match if in the same state (within ~65km)
  return VERIFIED_NER_HISTORICAL_LANDSLIDES.filter(
    (item) => item.state.toLowerCase().trim() === normState
  );
}

/**
 * Calculate distance in km between two lat/lon points (Haversine)
 */
export function getDistanceKm(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}
